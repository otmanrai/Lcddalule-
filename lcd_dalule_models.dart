class CommunitySuggestion {
  final String id;
  final String brand;
  final String model;
  final String suggestedCompatibleCode;
  int likesCount;
  int dislikesCount;
  bool isApproved;

  CommunitySuggestion({
    required this.id,
    required this.brand,
    required this.model,
    required this.suggestedCompatibleCode,
    this.likesCount = 0,
    this.dislikesCount = 0,
    this.isApproved = false,
  });

  // Threshold Rule: likesCount > 50 && likesCount > dislikesCount
  void vote(bool isLike) {
    if (isLike) {
      likesCount++;
    } else {
      dislikesCount++;
    }
    
    if (likesCount > 50 && likesCount > dislikesCount) {
      isApproved = true;
    }
  }
}

